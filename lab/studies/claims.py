"""Regenerate the claims table of tutorial/CLAIMS.md from the accepted results in tutorial/assets.

    python lab/studies/claims.py [--check]

Each claim names its study and output file; its value and status are computed
from that file, never typed. Status is "verified" when the result exists and
meets the claim's criterion, "not met" when it exists and does not, "pilot"
when only the pilot's result exists, and "pending" or "blocked" otherwise. The
table sits between marker lines and is replaced whole.
"""

import argparse
import json
from pathlib import Path
import sys

TUTORIAL = Path(__file__).resolve().parents[2] / "tutorial"
RESULTS = TUTORIAL / "assets" / "results" / "calibration"
CLAIMS = TUTORIAL / "CLAIMS.md"
BEGIN = "<!-- claims:begin (generated by studies/claims.py) -->"
END = "<!-- claims:end -->"


def load(relative):
    path = RESULTS / relative
    return json.loads(path.read_text()) if path.exists() else None


SYMBOLS = {"initial_variance": "v₀", "theta": "θ", "vol_of_vol": "σ_v", "rho": "ρ", "hurst": "H", "eta": "η"}


def pct(x, digits=0):
    return f"{100 * x:.{digits}f}%"


def c1():
    s = load("spy/surface.json")
    if s is None:
        return "—", "blocked: no chain source reachable (premium endpoints; Cboe and Yahoo hosts not allowed)"
    exponent = s["skew_power_law"]["exponent"]
    value = (f"exponent {exponent:.2f} from one week to one year, SPY on {s['diagnostics']['valuation']} "
             f"(the SPX literature's −0.4 is the reference)")
    return value, ("verified (within 0.1 of −0.4)" if abs(exponent + 0.4) <= 0.1 else "not met")


def identification(prefix):
    """S2's contraction, and the within-smile correlation of eta and rho: a ridge shows as a correlation near 1."""
    v = load(f"{prefix}/s2/validation.json")
    if v is None:
        return None
    c = v["contraction"]
    corr = (v.get("posterior_correlation_logit") or {}).get("eta|rho")
    value = f"contraction: ρη {c['rho_eta']:.2f}, η {c['eta']:.2f}, ρ {c['rho']:.2f}, H {c['hurst']:.2f}"
    if corr:
        value += (f"; within-smile correlation of η and ρ (logit coordinates) median {corr['median']:.2f}, "
                  f"10% to 90%: {corr['q10']:.2f} to {corr['q90']:.2f}")
    best = c["rho_eta"] > max(c["eta"], c["rho"])
    ridge = corr is not None and corr["median"] > 0.8
    return value, best, ridge


def c2():
    for prefix, label in (("rough", "full"), ("rough-pilot", "pilot")):
        found = identification(prefix)
        if found:
            value, best, ridge = found
            if best and ridge:
                status = "verified"
            elif best:
                status = "partly: ρη is identified best, but η and ρ are identified individually too (no long ridge)"
            else:
                status = "not met"
            return value, (status if label == "full" else f"pilot, {status}")
    return "—", "pending: rough bank"


def products_claim(prefix):
    p = load(f"{prefix}/s7/products.json")
    if p is None:
        return None
    var = max(s["products"]["variance_swap"]["range_90_relative"] for s in p["surfaces"])
    fwd = [s["products"]["forward_start_call"]["reserve_short_relative"] for s in p["surfaces"]]
    vol = [s["products"]["volatility_swap"]["range_90_relative"] for s in p["surfaces"]]
    return var, fwd, vol


def c3():
    for prefix, label in (("rough", "full"), ("rough-pilot", "pilot")):
        found = products_claim(prefix)
        if found is None:
            continue
        var, fwd, vol = found
        value = (f"variance-swap range ≤ {pct(var, 2)}; forward-start reserve {pct(min(fwd), 1)} to {pct(max(fwd), 1)} "
                 f"of price; volatility-swap range {pct(min(vol), 1)} to {pct(max(vol), 1)}")
        met = var < 1e-3 and min(vol) > 0
        status = "verified" if met else "not met"
        if label == "pilot":
            status = f"pilot, {status} (ranges from the pilot network, whose intervals are too wide: S5)"
        return value, status
    return "—", "pending: rough bank"


def c4():
    for prefix, label in (("rough", "full"), ("rough-pilot", "pilot")):
        p = load(f"{prefix}/s6/classical.json")
        if p is None:
            continue
        s = p["summary"]
        m = s["modes"]
        gn = s["gauss_newton_coverage_90"] or {}
        value = (f"mean {m['mean']:.1f} distinct optima; {pct(m['share_with_two_or_more'])} of {s['surfaces']} smiles with "
                 "two or more; Gauss–Newton 90% coverage "
                 + ", ".join(f"{SYMBOLS.get(k, k)} {pct(v)}" for k, v in gn.items())
                 + f"; no interval on {s['gauss_newton_singular']} (optimum at the prior's edge)")
        status = "verified" if m["share_with_two_or_more"] >= 0.5 else "not met: one optimum on most smiles"
        return value, (status if label == "full" else f"pilot, {status}")
    return "—", "pending: rough bank"


def c5():
    r = load("heston/s3/heston-check.json")
    if r is None:
        return "—", "pending"
    import numpy as np

    errors = np.array([s["network_vs_reweighted"]["standardized_mean_error"] for s in r["surfaces"]])
    widths = np.array([s["network_vs_reweighted"]["width_ratio"] for s in r["surfaces"]])
    passed = (errors < 0.3) & (np.abs(widths - 1) < 0.25)
    labels = ("v₀", "θ", "σ_v", "ρ")
    chains = r["summary"]["chain_checks"]
    value = (f"network alone, share of {len(r['surfaces'])} smiles within the criterion: "
             + ", ".join(f"{l} {pct(passed[:, j].mean())}" for j, l in enumerate(labels))
             + f" (all four {pct(passed.all(axis=1).mean())}); median mean error "
             + ", ".join(f"{l} {np.median(errors[:, j]):.2f}" for j, l in enumerate(labels))
             + f" sd; network plus importance sampling agrees with exact MCMC on "
               f"{sum(c['reweighted_vs_chain'] for c in chains)} of {len(chains)}")
    status = "verified" if passed.all(axis=1).mean() >= 0.9 else "not met for the network alone"
    return value, status


def c6():
    import numpy as np

    rows = []
    status = "pending"
    for prefix in ("heston", "rough", "rough-pilot"):
        r = load(f"{prefix}/s4/pricer-route.json")
        if r is None:
            continue
        s = r["summary"]
        errors = np.array([x["agreement"]["standardized_mean_error"] for x in r["surfaces"]])
        widths = np.array([x["agreement"]["width_ratio"] for x in r["surfaces"]])
        passed = (errors < 0.3) & (np.abs(widths - 1) < 0.25)
        shares = ", ".join(f"{SYMBOLS.get(n, n)} {pct(passed[:, j].mean())}" for j, n in enumerate(r["parameters"]))
        rows.append(f"{prefix}: {pct(s['pass_rate'])} of {len(r['surfaces'])} agree on all parameters ({shares}); "
                    f"pricer RMS error {s['pricer']['held_out_rms_error_in_noise_sd']['median_over_contracts']:.2f} σ_c "
                    "(median contract)")
        status = "verified" if s["pass_rate"] >= 0.9 else "not met for the network alone"
    exact = load("heston/s4-exact/pricer-route.json")
    if exact is not None:
        e = exact["summary"]["pricer_vs_exact"]
        rows.append(f"Heston pricer route against the exact posterior: {pct(e['pass_rate'])} of {e['surfaces']} agree")
    return ("; ".join(rows) or "—"), status


def c7():
    parts, statuses = [], []
    for prefix, label in (("heston", "Heston"), ("rough", "rough"), ("rough-pilot", "rough pilot")):
        v = load(f"{prefix}/s2/validation.json")
        if v is None:
            continue
        passed = v["sbc"]["passed"]
        cover = v["coverage"]["0.95"]["coverage"]
        failed = [SYMBOLS.get(n, "ρη" if n == "rho_eta" else n) for n, ok in zip(v["targets"], passed) if not ok]
        parts.append(f"{label}: SBC {sum(passed)}/{len(passed)} targets inside the band on {v['surfaces']:,} smiles; "
                     f"95% coverage {min(cover) * 100:.1f}–{max(cover) * 100:.1f}%")
        if prefix == "heston" and "contraction" in v:
            parts.append("Heston contraction " + ", ".join(f"{SYMBOLS.get(n, n)} {x:.2f}"
                                                         for n, x in v["contraction"].items()))
        statuses.append(f"{label} " + ("verified" if all(passed) else f"not met ({', '.join(failed)} outside the band)"))
    audit = load("rough-pilot/s5/audit.json") or load("rough/s5/audit.json")
    if audit:
        parts.append(f"audit flags {pct(audit['summary']['flag_rate_khat_above_0_7'])} of {audit['summary']['surfaces']} "
                     "rough smiles at k̂ > 0.7")
    if not parts:
        return "—", "pending"
    if load("rough/s2/validation.json") is None:
        statuses.append("full rough bank pending")
    return "; ".join(parts), "; ".join(statuses)


def c8():
    c = load("costs/costs.json")
    if c is None:
        return "—", "pending"
    value = (f"one rough likelihood evaluation {c['rough_likelihood_evaluation_cpu_s']['median']:.1f} CPU-s; exact rough "
             f"posterior at least {c['exact_rough_posterior']['cpu_hours']:.0f} CPU-h (extrapolated, a lower bound)")
    # The claim is about the rough-Bergomi network; the Heston network is the fallback only when it is missing.
    amortized = c.get("rough_amortized_posterior_1000_draws_cpu_s") or c.get("heston_amortized_posterior_1000_draws_cpu_s")
    if amortized:
        which = "rough" if "rough_amortized_posterior_1000_draws_cpu_s" in c else "Heston"
        value += (f"; the {which} network {amortized['wall_median']:.1f} s on the clock "
                  f"({amortized['median']:.1f} CPU-s) for 1,000 draws")
    if "heston_likelihood_evaluation_cpu_s" in c:
        value += (f"; Heston likelihood {1000 * c['heston_likelihood_evaluation_cpu_s']['median']:.0f} ms at one "
                  f"quadrature rung, exact Heston posterior about {c['exact_heston_posterior']['cpu_seconds']:.0f} "
                  "CPU-s at one rung")
    bank_quality = load("heston/s1/bank-quality.json")
    if bank_quality:
        g = bank_quality["generation"]
        value += f"; Heston bank {g['surfaces']:,} smiles in {g['cpu_seconds'] / 60:.0f} CPU-min"
    training = TUTORIAL / "assets" / "checkpoints" / "heston" / "training.json"
    if training.exists():
        t = json.loads(training.read_text())
        value += (f"; Heston network {t['training']['epochs']} epochs in "
                  f"{t['timing_seconds']['training_including_compile'] / 60:.0f} min on {t['cpu_count']} cores")
    return value, "verified"


def c9():
    for prefix, label in (("rough", "full"), ("rough-pilot", "pilot")):
        a = load(f"{prefix}/s7-across/across-models.json")
        if a is None:
            continue
        forward = [s["products"]["forward_start_call"] for s in a["surfaces"]]
        gaps = [f["gap_between_points_relative"] for f in forward]
        apart = sum(not f["ranges_overlap"] for f in forward)
        value = (f"forward-start, Heston minus rough at the least-squares points: {pct(min(gaps), 1)} to "
                 f"{pct(max(gaps), 1)} of the rough price on {len(forward)} rough-Bergomi smiles; the two 90% "
                 f"posterior ranges are disjoint on {apart} of {len(forward)}")
        met = apart == len(forward)
        status = ("verified" if met else "not met: the ranges overlap") if label == "full" else \
            f"pilot ({'apart' if met else 'ranges overlap'} on the pilot's smiles)"
        return value, status
    return "—", "pending: rough bank"


def c10():
    found = products_claim("heston")
    if found is None:
        return "—", "pending"
    var, fwd, vol = found
    return (f"forward-start reserve {pct(min(fwd), 1)} to {pct(max(fwd), 1)} of price; variance-swap range up to "
            f"{pct(var, 1)}"), "verified"


def c11():
    p = load("heston/s6/classical.json")
    if p is None:
        return "—", "pending"
    s = p["summary"]
    gn = s["gauss_newton_coverage_90"] or {}
    post = s["posterior_coverage_90"]
    value = (f"90% coverage, Gauss–Newton {min(gn.values()) * 100:.0f}–{max(gn.values()) * 100:.0f}% "
             f"against posterior {min(post.values()) * 100:.0f}–{max(post.values()) * 100:.0f}% on {s['surfaces']} smiles; "
             f"no Gauss–Newton interval on {s['gauss_newton_singular']} (singular information matrix); one optimum on "
             f"{pct(1 - s['modes']['share_with_two_or_more'])} of smiles"
             if gn else "no Gauss–Newton interval computed")
    return value, "verified"


CLAIMS_LIST = [
    ("C1", "The SPY ATM skew follows a power law in T, with an exponent near −0.4", "S8", "spy/surface.json", c1),
    ("C2", "A smile identifies ρη and H; η and ρ separately only along a ridge", "S2", "rough/s2/validation.json", c2),
    ("C3", "Under rough Bergomi the variance swap's posterior range is zero; the volatility swap's and the "
           "forward-start's are not; the forward-start reserve is a stated share of its price", "S7",
     "rough/s7/products.json", c3),
    ("C4", "Multi-start least squares lands on several optima along the ridge; a regularized fit picks one by "
           "its penalty", "S6", "rough/s6/classical.json", c4),
    ("C5", "The amortized posterior agrees with the exact Heston posterior: means within 0.3 posterior sd, 90% "
           "widths within 25%", "S3", "heston/s3/heston-check.json", c5),
    ("C6", "The amortized posterior and MCMC on a neural pricer agree within the same criterion", "S4",
     "*/s4/pricer-route.json", c6),
    ("C7", "SBC passes on held-out smiles; the audit flags a stated share of smiles", "S2, S5",
     "*/s2/validation.json, */s5/audit.json", c7),
    ("C8", "One Monte Carlo likelihood evaluation costs seconds, the exact posterior hours, the network about a "
           "second", "S9", "costs/costs.json", c8),
    ("C9", "Heston and rough Bergomi calibrated to the same smile price the forward-start apart", "S7",
     "rough*/s7-across/across-models.json", c9),
    ("C10", "Under Heston every product carries a range, the variance swap included, because Heston's "
            "forward-variance curve depends on its parameters", "S7", "heston/s7/products.json", c10),
    ("C11", "Gauss–Newton intervals and posterior intervals cover the truth at the stated rates on Heston smiles",
     "S6", "heston/s6/classical.json", c11),
]


def table():
    lines = ["| # | Claim | Study | Output | Value | Status |", "|---|---|---|---|---|---|"]
    for number, claim, study, output, fn in CLAIMS_LIST:
        value, status = fn()
        lines.append(f"| {number} | {claim} | {study} | `results/calibration/{output}` | {value} | {status} |")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = CLAIMS.read_text()
    if BEGIN not in text or END not in text:
        raise SystemExit(f"{CLAIMS} lacks the marker lines")
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    updated = f"{head}{BEGIN}\n{table()}\n{END}{tail}"
    if args.check:
        print("current" if updated == text else "stale")
        sys.exit(0 if updated == text else 1)
    CLAIMS.write_text(updated)
    print(table())


if __name__ == "__main__":
    main()
