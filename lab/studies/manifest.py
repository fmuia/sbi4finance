"""Regenerate the "Copied artifacts" table of tutorial_final/MANIFEST.md from the files present.

    python tutorial_final/studies/manifest.py [--check]

Every file under tutorial_final/results/ and tutorial_final/checkpoints/ is
listed with its size and SHA-256, grouped by folder. The table sits between two
marker lines in MANIFEST.md and is replaced whole; the rest of the file is
untouched. With --check the script only reports whether the table is current
and exits non-zero if it is not.
"""

import argparse
import hashlib
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "MANIFEST.md"
BEGIN = "<!-- artifacts:begin (generated by studies/manifest.py) -->"
END = "<!-- artifacts:end -->"


def table():
    rows = []
    for top in ("results", "checkpoints"):
        base = ROOT / top
        if not base.exists():
            continue
        for path in sorted(p for p in base.rglob("*") if p.is_file()):
            digest = hashlib.sha256(path.read_bytes()).hexdigest()
            rows.append((str(path.relative_to(ROOT)), path.stat().st_size, digest))
    if not rows:
        return "No artifacts copied yet.", 0
    lines = ["| File | Bytes | SHA-256 |", "|---|---:|---|"]
    lines += [f"| `{name}` | {size:,} | `{digest}` |" for name, size, digest in rows]
    return "\n".join(lines), len(rows)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = MANIFEST.read_text()
    if BEGIN not in text or END not in text:
        raise SystemExit(f"{MANIFEST} lacks the marker lines")
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    body, count = table()
    updated = f"{head}{BEGIN}\n{body}\n{END}{tail}"
    if args.check:
        print("current" if updated == text else "stale")
        sys.exit(0 if updated == text else 1)
    MANIFEST.write_text(updated)
    print(f"{MANIFEST}: {count} artifacts")


if __name__ == "__main__":
    main()
