"""Refresh the tutorial's copies of lab files and the "Copied artifacts" table of tutorial/MANIFEST.md.

    python lab/studies/manifest.py [--check]

tutorial/assets/ holds everything the notebooks read. Accepted study results
and checkpoints enter it through accept.py, and the exact Heston posterior on
SPY through lab/checks/heston_spy_exact.py. The files in EXPORTS are copies of
lab and course files, refreshed here. Every file under tutorial/assets/ is then
listed with its size, SHA-256 and, for a copy, its source. The table sits
between two marker lines in MANIFEST.md and is replaced whole; the rest of the
file is untouched. With --check the script changes nothing, reports whether the
copies match their sources and the table is current, and exits non-zero if not.
"""

import argparse
import hashlib
from pathlib import Path
import shutil
import sys

REPO = Path(__file__).resolve().parents[2]
ASSETS = REPO / "tutorial" / "assets"
MANIFEST = REPO / "tutorial" / "MANIFEST.md"
BEGIN = "<!-- artifacts:begin (generated by lab/studies/manifest.py) -->"
END = "<!-- artifacts:end -->"
# Path under tutorial/assets/ -> its source, relative to the repository root.
EXPORTS = {
    "quick-checks/bs_hierarchy.json": "lab/checks/bs_hierarchy.json",
    "quick-checks/heston_checks.json": "lab/checks/heston_checks.json",
    "quick-checks/heston_checks-3_x_5_grid_kappa_free.npy": "lab/checks/heston_checks-3_x_5_grid_kappa_free.npy",
    "quick-checks/heston_checks-full_grid_kappa_free.npy": "lab/checks/heston_checks-full_grid_kappa_free.npy",
    "quick-checks/long_end/long_end.json": "lab/checks/long_end/long_end.json",
    "quick-checks/long_end/long_end_extra.json": "lab/checks/long_end/long_end_extra.json",
    "quick-checks/rough_checks.json": "lab/checks/rough_checks.json",
    "images/ladder.png": "tutorial/curriculum/images/ladder.png",
    "images/l10-credible-vs-confidence.png": "course/images/l10-credible-vs-confidence.png",
}


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def stale_exports():
    return [name for name, source in EXPORTS.items()
            if not (ASSETS / name).exists() or sha256(ASSETS / name) != sha256(REPO / source)]


def table():
    rows = []
    for path in sorted(p for p in ASSETS.rglob("*") if p.is_file()):
        name = str(path.relative_to(ASSETS))
        source = f"`{EXPORTS[name]}`" if name in EXPORTS else ""
        rows.append(f"| `{name}` | {path.stat().st_size:,} | `{sha256(path)}` | {source} |")
    if not rows:
        return "No artifacts copied yet.", 0
    return "\n".join(["| File | Bytes | SHA-256 | Copy of |", "|---|---:|---|---|"] + rows), len(rows)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = stale_exports()
    if not args.check:
        for name in stale:
            (ASSETS / name).parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(REPO / EXPORTS[name], ASSETS / name)
    text = MANIFEST.read_text()
    if BEGIN not in text or END not in text:
        raise SystemExit(f"{MANIFEST} lacks the marker lines")
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    body, count = table()
    updated = f"{head}{BEGIN}\n{body}\n{END}{tail}"
    if args.check:
        for name in stale:
            print(f"stale copy: {name} differs from {EXPORTS[name]}")
        print("current" if updated == text and not stale else "stale")
        sys.exit(0 if updated == text and not stale else 1)
    MANIFEST.write_text(updated)
    print(f"{MANIFEST}: {count} artifacts, {len(stale)} copies refreshed")


if __name__ == "__main__":
    main()
